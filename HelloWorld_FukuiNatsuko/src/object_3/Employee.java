package object_3;

// Employeeクラスを作成
public class Employee {
	String employeed;
	String name;

	public void setEmployeed(String id) {
		this.employeed = id;
	}

	public String getEmployeed() {
		return this.employeed;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getName() {
		return this.name;
	}

}
